// src/messages/helper/applet.ts — the AppleScript of the Tropos Messages Helper app, generated per user
import { dirname, join } from "node:path";

/** Raise this only when the script must change: a rebuilt helper loses its Full Disk Access and Automation grants. */
export const HELPER_VERSION = 1;
export const HELPER_BUNDLE_ID = "com.troposlabs.messages-helper";
export const HELPER_NAME = "Tropos Messages Helper";

/** An AppleScript string literal for `s`: backslashes and double quotes escaped, nothing else changed. */
export function appleScriptString(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/** The per-install request token sits next to the run folder: `<runDir>/../token`. */
export function helperTokenPath(runDir: string): string {
  return join(dirname(runDir), "token");
}

/**
 * The helper's script. The only things written into it are three paths (the run folder, the token file and
 * the user's home), as escaped literals; every request (token, action, arguments, message text) is read from
 * files at run time into variables, so nothing a request carries can ever become script text, and shell
 * commands only ever see it through `quoted form of`.
 *
 * Protocol, in `runDir`: `req-<id>.txt` holds the install's token on line 1 (compared with the token file,
 * which is read at run time and never through a symlink), the action on line 2 and one argument per
 * following line; a `send-*` request's text is `req-<id>.body`. The helper deletes both as soon as it has
 * read them (so a send is never repeated), does the work, then writes `res-<id>.txt.tmp` and renames it to
 * `res-<id>.txt`: line 1 `ok` or `error`, line 2 a code (`0` when ok; `bad-request`, `unauthorized`, `eperm`
 * or an AppleScript error number such as `-1743` otherwise), then the result's lines or the error message.
 *
 * Actions: `status` → `fda=yes|no`; `probe` → `accounts=<n>` (asks Messages, which raises the Automation
 * prompt); `snapshot <dest>` copies chat.db with its -wal/-shm into `dest`; `contacts <dest>` copies each
 * `AddressBook-v22.abcddb` (with -wal/-shm) to `dest/contacts-<n>/` and lists those paths relative to `dest`;
 * `attachment <src> <dest>` copies one file from Messages' Attachments folder into `dest` and replies with
 * the copy's path; `send-handle <handle> <iMessage|SMS>` and `send-chat <guid>` send the body;
 * `open-settings fda|automation` opens that Privacy pane.
 *
 * Paths are checked physically, not just by spelling: the run folder must be a real directory (not a
 * symlink) owned by the user, or the helper does nothing; every `dest` must be an existing real directory
 * named `snap-…` directly inside it (the caller creates it); an attachment must be a real file (not a
 * symlink) whose physical folder lies inside the physical Attachments folder. Every write then happens in
 * one shell step that changes into the checked folder's physical path and confirms it with `pwd -P` before
 * touching anything, so swapping a folder for a symlink after the check can't redirect it; files are
 * created with the shell's noclobber (`set -C`), which never writes through a link planted at the name.
 *
 * The script has no `property` or `global`: an applet saves those back into its bundle when it quits, which
 * would break the signature and with it the grants.
 */
export function appletSource(o: { runDir: string; userHome: string }): string {
  return `-- ${HELPER_NAME} ${HELPER_VERSION}: generated by Tropos Code. Edits are lost when Tropos rebuilds it.

on run
	processQueue()
end run

on reopen
	processQueue()
end reopen

on helperRunDir()
	return ${appleScriptString(o.runDir)}
end helperRunDir

on helperTokenPath()
	return ${appleScriptString(helperTokenPath(o.runDir))}
end helperTokenPath

on helperUserHome()
	return ${appleScriptString(o.userHome)}
end helperUserHome

on chatDbPath()
	return helperUserHome() & "/Library/Messages/chat.db"
end chatDbPath

-- Handles every waiting request, including ones that arrive while it works; each one at most once.
on processQueue()
	set runDir to helperRunDir()
	if isLink(runDir) or not isDir(runDir) or not isOwned(runDir) then return
	try
		set physRun to physicalDir(runDir)
	on error
		return
	end try
	set handled to {}
	repeat 1000 times
		set fresh to false
		try
			set entryNames to paragraphs of (do shell script "/bin/ls " & quoted form of runDir)
		on error
			return
		end try
		repeat with entryRef in entryNames
			set entryName to contents of entryRef
			considering case
				set isRequest to (entryName starts with "req-") and (entryName ends with ".txt") and (length of entryName > 8)
			end considering
			if isRequest then
				set reqId to text 5 thru -5 of entryName
				if handled does not contain reqId then
					set end of handled to reqId
					set fresh to true
					handleRequest(reqId, physRun)
				end if
			end if
		end repeat
		if not fresh then exit repeat
	end repeat
end processQueue

on handleRequest(reqId, physRun)
	set reqPath to physRun & "/req-" & reqId & ".txt"
	set bodyPath to physRun & "/req-" & reqId & ".body"
	set reqLines to {}
	set theBody to missing value
	set authorized to false
	if not isLink(reqPath) then
		try
			set reqLines to paragraphs of (read (POSIX file reqPath) as «class utf8»)
		end try
	end if
	if (count of reqLines) > 1 then
		set expected to readToken()
		considering case
			set authorized to (expected is not "") and ((item 1 of reqLines) is expected)
			set isSend to (item 2 of reqLines) starts with "send-"
		end considering
		if authorized and isSend and not isLink(bodyPath) then
			try
				set theBody to read (POSIX file bodyPath) as «class utf8»
			end try
		end if
	end if
	removeFile(reqPath)
	removeFile(bodyPath)
	if (count of reqLines) < 2 then
		set outcome to badRequest("the request was empty or unreadable")
	else if not authorized then
		set outcome to {"error", "unauthorized", "the request did not carry this install's token"}
	else
		try
			set outcome to runAction(item 2 of reqLines, rest of (rest of reqLines), theBody)
		on error errMsg number errNum
			set outcome to {"error", errNum as text, errMsg}
		end try
	end if
	writeReply(physRun, reqId, outcome)
end handleRequest

-- The install's token, read fresh each time; empty when it is missing, unreadable or a symlink.
on readToken()
	set tokenPath to helperTokenPath()
	if isLink(tokenPath) then return ""
	try
		set tokenText to read (POSIX file tokenPath) as «class utf8»
	on error
		return ""
	end try
	if (count of paragraphs of tokenText) is 0 then return ""
	return paragraph 1 of tokenText
end readToken

on runAction(act, reqArgs, theBody)
	considering case
		if act is "status" then return doStatus()
		if act is "probe" then return doProbe()
		if act is "snapshot" then return doSnapshot(reqArgs)
		if act is "contacts" then return doContacts(reqArgs)
		if act is "attachment" then return doAttachment(reqArgs)
		if act is "send-handle" then return doSendHandle(reqArgs, theBody)
		if act is "send-chat" then return doSendChat(reqArgs, theBody)
		if act is "open-settings" then return doOpenSettings(reqArgs)
	end considering
	return badRequest("unknown action " & act)
end runAction

on doStatus()
	set chatDb to chatDbPath()
	try
		do shell script "/usr/bin/head -c 1 " & quoted form of chatDb & " > /dev/null"
		return {"ok", "0", "fda=yes"}
	on error
		return {"ok", "0", "fda=no"}
	end try
end doStatus

on doProbe()
	try
		with timeout of 30 seconds
			tell application "Messages" to set n to count of accounts
		end timeout
		return {"ok", "0", "accounts=" & n}
	on error errMsg number errNum
		return {"error", errNum as text, errMsg}
	end try
end doProbe

on doSnapshot(reqArgs)
	if (count of reqArgs) is not 1 then return badRequest("snapshot takes one folder")
	set dest to item 1 of reqArgs
	set physDest to snapFolder(dest)
	if physDest is "" then return badRequest("the snapshot folder must be an existing snap- folder in the helper's run folder")
	set chatDb to chatDbPath()
	try
		copyChecked(chatDb, physDest, "chat.db")
		copyIfExists(chatDb & "-wal", physDest, "chat.db-wal")
		copyIfExists(chatDb & "-shm", physDest, "chat.db-shm")
	on error errMsg number errNum
		return shellFailure(errMsg, errNum)
	end try
	return {"ok", "0", "chat.db"}
end doSnapshot

on doContacts(reqArgs)
	if (count of reqArgs) is not 1 then return badRequest("contacts takes one folder")
	set dest to item 1 of reqArgs
	set physDest to snapFolder(dest)
	if physDest is "" then return badRequest("the contacts folder must be an existing snap- folder in the helper's run folder")
	set abDir to helperUserHome() & "/Library/Application Support/AddressBook"
	set outcome to {"ok", "0"}
	if not isDir(abDir) then return outcome
	try
		set found to paragraphs of (do shell script "/usr/bin/find " & quoted form of abDir & " -name AddressBook-v22.abcddb -type f")
		set n to 0
		repeat with foundRef in found
			set dbPath to contents of foundRef
			if dbPath is not "" then
				set n to n + 1
				set subName to "contacts-" & n
				do shell script pinTo(physDest) & "/bin/mkdir -m 700 ./" & quoted form of subName
				set physSub to physDest & "/" & subName
				copyChecked(dbPath, physSub, "AddressBook-v22.abcddb")
				copyIfExists(dbPath & "-wal", physSub, "AddressBook-v22.abcddb-wal")
				copyIfExists(dbPath & "-shm", physSub, "AddressBook-v22.abcddb-shm")
				set end of outcome to subName & "/AddressBook-v22.abcddb"
			end if
		end repeat
	on error errMsg number errNum
		return shellFailure(errMsg, errNum)
	end try
	return outcome
end doContacts

on doAttachment(reqArgs)
	if (count of reqArgs) is not 2 then return badRequest("attachment takes a file and a folder")
	set src to item 1 of reqArgs
	set dest to item 2 of reqArgs
	set physSrcDir to attachmentFolder(src)
	if physSrcDir is "" then return badRequest("only files in Messages' Attachments folder can be copied")
	set physDest to snapFolder(dest)
	if physDest is "" then return badRequest("the attachment folder must be an existing snap- folder in the helper's run folder")
	set fileName to lastComponent(src)
	set copied to dest & "/" & fileName
	try
		copyChecked(physSrcDir & "/" & fileName, physDest, fileName)
	on error errMsg number errNum
		return shellFailure(errMsg, errNum)
	end try
	return {"ok", "0", copied}
end doAttachment

on doSendHandle(reqArgs, theBody)
	if (count of reqArgs) is not 2 then return badRequest("send-handle takes a handle and a service")
	if theBody is missing value then return badRequest("there was no text to send")
	set theHandle to item 1 of reqArgs
	set theService to item 2 of reqArgs
	considering case
		set useIMessage to theService is "iMessage"
		set useSMS to theService is "SMS"
	end considering
	if not (useIMessage or useSMS) then return badRequest("the service must be iMessage or SMS")
	try
		with timeout of 170 seconds
			if useIMessage then
				tell application "Messages"
					send theBody to participant theHandle of (1st account whose service type = iMessage)
				end tell
			else
				tell application "Messages"
					send theBody to participant theHandle of (1st account whose service type = SMS)
				end tell
			end if
		end timeout
	on error errMsg number errNum
		return {"error", errNum as text, errMsg}
	end try
	return {"ok", "0", "sent"}
end doSendHandle

on doSendChat(reqArgs, theBody)
	if (count of reqArgs) is not 1 then return badRequest("send-chat takes a chat id")
	if theBody is missing value then return badRequest("there was no text to send")
	set theChat to item 1 of reqArgs
	try
		with timeout of 170 seconds
			tell application "Messages"
				send theBody to chat id theChat
			end tell
		end timeout
	on error errMsg number errNum
		return {"error", errNum as text, errMsg}
	end try
	return {"ok", "0", "sent"}
end doSendChat

on doOpenSettings(reqArgs)
	if (count of reqArgs) is not 1 then return badRequest("open-settings takes fda or automation")
	set pane to item 1 of reqArgs
	considering case
		if pane is "fda" then
			open location "x-apple.systempreferences:com.apple.preference.security?Privacy_AllFiles"
			return {"ok", "0"}
		end if
		if pane is "automation" then
			open location "x-apple.systempreferences:com.apple.preference.security?Privacy_Automation"
			return {"ok", "0"}
		end if
	end considering
	return badRequest("open-settings takes fda or automation")
end doOpenSettings

-- True when the spelling of p starts with prefix, goes further, and has no way back out.
on isUnder(p, prefix)
	considering case
		if not (p starts with prefix) then return false
		if (length of p) is not greater than (length of prefix) then return false
		if p contains "/../" then return false
		if p ends with "/.." then return false
	end considering
	return true
end isUnder

-- The physical path of p when it is an existing real directory named snap-... directly inside the
-- physical run folder, else "".
on snapFolder(p)
	set runDir to helperRunDir()
	if not isUnder(p, runDir & "/snap-") then return ""
	set nm to lastComponent(p)
	considering case
		if not (nm starts with "snap-") then return ""
	end considering
	if isLink(p) or not isDir(p) then return ""
	try
		set physDest to physicalDir(p)
		set physRun to physicalDir(runDir)
	on error
		return ""
	end try
	considering case
		if physDest is not (physRun & "/" & nm) then return ""
	end considering
	return physDest
end snapFolder

-- The physical folder of p when p is a real file (not a symlink) inside the physical Attachments folder, else "".
on attachmentFolder(p)
	set attDir to helperUserHome() & "/Library/Messages/Attachments"
	if not isUnder(p, attDir & "/") then return ""
	set nm to lastComponent(p)
	if nm is "" or nm is "." or nm is ".." then return ""
	if isLink(p) or not isFile(p) then return ""
	try
		set physParent to physicalDir(parentOf(p))
		set physAtt to physicalDir(attDir)
	on error
		return ""
	end try
	considering case
		if (physParent is physAtt) or (physParent starts with (physAtt & "/")) then return physParent
	end considering
	return ""
end attachmentFolder

on physicalDir(p)
	return do shell script "cd -P -- " & quoted form of p & " && /bin/pwd -P"
end physicalDir

on isLink(p)
	try
		do shell script "/bin/test -L " & quoted form of p
		return true
	on error
		return false
	end try
end isLink

on isDir(p)
	try
		do shell script "/bin/test -d " & quoted form of p
		return true
	on error
		return false
	end try
end isDir

on isOwned(p)
	try
		do shell script "/bin/test -O " & quoted form of p
		return true
	on error
		return false
	end try
end isOwned

on isFile(p)
	try
		do shell script "/bin/test -f " & quoted form of p
		return true
	on error
		return false
	end try
end isFile

on lastComponent(p)
	set AppleScript's text item delimiters to "/"
	set nm to last text item of p
	set AppleScript's text item delimiters to ""
	return nm
end lastComponent

on parentOf(p)
	set AppleScript's text item delimiters to "/"
	set parts to text items of p
	if (count of parts) < 2 then
		set AppleScript's text item delimiters to ""
		return "/"
	end if
	set parentText to (items 1 thru -2 of parts) as text
	set AppleScript's text item delimiters to ""
	return parentText
end parentOf

-- The start of a shell step that works inside physFolder: it changes into it, confirms the physical path is
-- still the one that was checked (so a folder swapped for a symlink since is refused), and turns on noclobber,
-- so a file the step creates never writes through whatever was planted at its name.
on pinTo(physFolder)
	return "cd -P -- " & quoted form of physFolder & " || exit 1; [ \\"$(/bin/pwd -P)\\" = " & quoted form of physFolder & " ] || { echo 'the folder changed before the copy' >&2; exit 1; }; set -C; "
end pinTo

-- Copies src (never a symlink) to fileName inside the checked folder physFolder, in one shell step.
on copyChecked(src, physFolder, fileName)
	do shell script pinTo(physFolder) & "if [ -L " & quoted form of src & " ]; then echo 'refusing to copy a symlink' >&2; exit 1; fi; /bin/rm -f ./" & quoted form of fileName & " && /bin/cat -- " & quoted form of src & " > ./" & quoted form of fileName
end copyChecked

on copyIfExists(src, physFolder, fileName)
	if not isFile(src) then return
	copyChecked(src, physFolder, fileName)
end copyIfExists

on removeFile(p)
	try
		do shell script "/bin/rm -f " & quoted form of p
	end try
end removeFile

on badRequest(why)
	return {"error", "bad-request", why}
end badRequest

on shellFailure(errMsg, errNum)
	if errMsg contains "Operation not permitted" then return {"error", "eperm", errMsg}
	return {"error", errNum as text, errMsg}
end shellFailure

-- Writes the reply next to its final name, then renames it, so the client never reads half a reply. Both
-- happen in one step pinned to the run folder; mv -h replaces a link at the name instead of following it.
on writeReply(physRun, reqId, outcome)
	set tmpName to "res-" & reqId & ".txt.tmp"
	set resName to "res-" & reqId & ".txt"
	set AppleScript's text item delimiters to linefeed
	set outText to outcome as text
	set AppleScript's text item delimiters to ""
	try
		do shell script pinTo(physRun) & "/bin/rm -f ./" & quoted form of tmpName & " && /usr/bin/printf '%s' " & quoted form of outText & " > ./" & quoted form of tmpName & " && /bin/mv -f -h ./" & quoted form of tmpName & " ./" & quoted form of resName
	end try
end writeReply
`;
}
